-- Journal lines and entries serialize on the parent entry to prevent approval races.
create function accounting.guard_line() returns trigger language plpgsql security definer set search_path = '' as $$
declare s text; d date; eid bigint;
begin
 perform pg_advisory_xact_lock(620261116);
 eid := case when TG_OP='DELETE' then old.entry_id else new.entry_id end;
 if TG_OP='UPDATE' and new.entry_id<>old.entry_id then raise exception 'Cannot move journal lines'; end if;
 select status,entry_date into s,d from accounting.journal_entries where id=eid for update;
 if s is distinct from 'pending' then raise exception 'Only pending entries accept line changes'; end if;
 if exists(select 1 from accounting.accounting_periods where d between period_start and period_end and status<>'open') then raise exception 'Period is closed'; end if;
 if TG_OP='DELETE' then return old; end if;
 new.base_debit:=round(new.debit*new.exchange_rate,2);
 new.base_credit:=round(new.credit*new.exchange_rate,2);
 return new;
end $$;
create trigger guard_line before insert or update or delete on accounting.journal_lines for each row execute function accounting.guard_line();
create function accounting.guard_entry() returns trigger language plpgsql security definer set search_path = '' as $$
declare total numeric; n integer; lim numeric;
begin
 if TG_OP='DELETE' then raise exception 'Journal entries cannot be deleted'; end if;
 -- Prevent entries or approvals in closed periods, including date moves out of a closed period.
 perform pg_advisory_xact_lock(620261116);
 if exists(select 1 from accounting.accounting_periods where new.entry_date between period_start and period_end and status<>'open') then raise exception 'Period is closed'; end if;
 if TG_OP='INSERT' then
  if new.status<>'pending' then raise exception 'New entries must be pending'; end if;
  new.created_by:=auth.uid(); new.approved_by:=null; new.approved_at:=null;
  new.voided_by:=null;new.voided_at:=null;new.void_reason:=null;
 else
  if new.status=old.status and not accounting.has_role(array['admin','finance_manager','accountant']) then raise exception 'Bookkeeper role required for editing'; end if;
  if exists(select 1 from accounting.accounting_periods where old.entry_date between period_start and period_end and status<>'open') then raise exception 'Original period is closed'; end if;
  if new.created_by is distinct from old.created_by or new.created_at is distinct from old.created_at then raise exception 'Creator is immutable'; end if;
  if old.status='voided' then raise exception 'Voided entries are immutable'; end if;
  if old.status='approved' and new.status<>'voided' then raise exception 'Approved entries are immutable'; end if;
  if new.status<>old.status then
   if not accounting.has_role(array['admin','finance_manager','approver']) then raise exception 'Approver role required'; end if;
   if new.status='approved' then
    if old.status<>'pending' or old.created_by is null or old.created_by=auth.uid() then raise exception 'A different user must approve'; end if;
    select count(*),coalesce(sum(base_debit-base_credit),0) into n,total from accounting.journal_lines where entry_id=old.id;
    if n<2 or total<>0 then raise exception 'At least two balanced lines required'; end if;
    select approval_limit into lim from accounting.staff where id=auth.uid() and active;
    if lim is not null and (select sum(base_debit) from accounting.journal_lines where entry_id=old.id)>lim then raise exception 'Approval limit exceeded'; end if;
    new.approved_by:=auth.uid(); new.approved_at:=now();
   elsif new.status='voided' then
    if nullif(btrim(new.void_reason),'') is null then raise exception 'Void reason required'; end if;
    new.voided_by:=auth.uid(); new.voided_at:=now();
   else raise exception 'Invalid transition'; end if;
   if (to_jsonb(new)-array['status','approved_by','approved_at','voided_by','voided_at','void_reason']) is distinct from (to_jsonb(old)-array['status','approved_by','approved_at','voided_by','voided_at','void_reason']) then raise exception 'Change status separately from entry content'; end if;
  elsif new.approved_by is distinct from old.approved_by or new.approved_at is distinct from old.approved_at or new.voided_by is distinct from old.voided_by or new.voided_at is distinct from old.voided_at then raise exception 'Approval metadata is managed by the database'; end if;
 end if;
 return new;
end $$;
