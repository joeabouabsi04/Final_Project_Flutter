create function accounting.audit_change() returns trigger language plpgsql security definer set search_path = '' as $$
begin
 insert into accounting.system_audit_log(entity_type,entity_id,action,actor_user_id,details)
 values(TG_TABLE_NAME,coalesce(new.id,old.id)::text,TG_OP,auth.uid(),jsonb_build_object('before',case when TG_OP<>'INSERT' then to_jsonb(old) end,'after',case when TG_OP<>'DELETE' then to_jsonb(new) end)::text);
 return coalesce(new,old);
end $$;
create function accounting.guard_period() returns trigger language plpgsql set search_path = '' as $$
begin
 perform pg_advisory_xact_lock(620261116);
 if TG_OP='UPDATE' and (new.period_start<>old.period_start or new.period_end<>old.period_end) then raise exception 'Period boundaries are immutable'; end if;
 if exists(select 1 from accounting.accounting_periods p where p.id<>new.id and daterange(p.period_start,p.period_end,'[]') && daterange(new.period_start,new.period_end,'[]')) then raise exception 'Overlapping period'; end if;
 if TG_OP='UPDATE' and old.status<>'open' and new.status='open' and nullif(btrim(new.reopen_reason),'') is null then raise exception 'Reopen reason required'; end if;
 if new.status<>'open' then new.closed_by:=auth.uid();new.closed_at:=now(); end if;
